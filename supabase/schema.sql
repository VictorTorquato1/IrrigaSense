-- Schema mínimo para IrrigaSense
-- Ajuste este SQL no painel do Supabase conforme a estrutura real do projeto.

create table if not exists public.leituras (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  device_id text not null default 'irrigasense-default',
  session_id text null,
  vazao numeric(10,2) not null default 0,
  agua_usada numeric(10,2) not null default 0,
  bomba_ligada boolean not null default false,
  pulsos integer null,
  tempo_esp32_ms bigint null
);

create table if not exists public.alertas (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  device_id text not null default 'irrigasense-default',
  session_id text null,
  tipo text not null,
  mensagem text not null,
  vazao_l_min numeric(10,2) null,
  limite_minimo numeric(10,2) null,
  limite_maximo numeric(10,2) null
);

create table if not exists public.sessoes (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  device_id text not null default 'irrigasense-default',
  session_id text not null unique,
  iniciada_em timestamptz null,
  finalizada_em timestamptz null,
  volume_total_l numeric(10,2) not null default 0,
  vazao_media_l_min numeric(10,2) not null default 0,
  status text not null default 'ativa'
);

create table if not exists public.configuracoes (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  device_id text not null unique,
  vazao_minima numeric(10,2) not null default 0,
  vazao_maxima numeric(10,2) not null default 10,
  updated_at timestamptz not null default now()
);

alter table public.leituras enable row level security;
alter table public.alertas enable row level security;
alter table public.sessoes enable row level security;
alter table public.configuracoes enable row level security;

